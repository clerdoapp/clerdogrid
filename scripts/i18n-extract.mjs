// Rebuilds src/ui/i18n/en.ts from the source: every literal passed to T(), t(), Tr(), tr() or N() is a key.
// Existing English text for a key is kept (plural forms), new keys get their own text, unused keys are dropped.
// Run: node scripts/i18n-extract.mjs   (then add the new keys to every language file; tests/i18n.test.ts checks)
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import ts from 'typescript';

const root = new URL('../src', import.meta.url).pathname;
const walk = (d, out = []) => { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p, out); else if (/\.tsx?$/.test(f)) out.push(p); } return out; };
const files = walk(root).filter((f) => !f.includes('/ui/i18n/') && !f.includes('/engine/') && !f.includes('/cli/'));
const keys = new Map();
for (const f of files) {
  const sf = ts.createSourceFile(f, readFileSync(f, 'utf8'), 99, true, f.endsWith('x') ? 4 : 3);
  // Only the translation functions imported from ui/i18n count (some files have their own T).
  const names = new Set();
  for (const st of sf.statements) {
    if (!ts.isImportDeclaration(st) || !/\/i18n['"]?$/.test(st.moduleSpecifier.getText(sf).replace(/['"]/g, ''))) continue;
    const b = st.importClause?.namedBindings;
    if (b && ts.isNamedImports(b)) for (const el of b.elements) if (['t', 'T', 'tr', 'Tr', 'N'].includes((el.propertyName ?? el.name).text)) names.add(el.name.text);
  }
  if (!names.size) continue;
  const visit = (n) => {
    if (ts.isCallExpression(n) && ts.isIdentifier(n.expression) && names.has(n.expression.text)) {
      const take = (a) => {
        if (!a) return;
        if (ts.isStringLiteral(a) || ts.isNoSubstitutionTemplateLiteral(a)) { if (!keys.has(a.text)) keys.set(a.text, relative(root, f)); return; }
        if (ts.isParenthesizedExpression(a)) take(a.expression);
        else if (ts.isConditionalExpression(a)) { take(a.whenTrue); take(a.whenFalse); }
        else if (ts.isBinaryExpression(a) && [ts.SyntaxKind.BarBarToken, ts.SyntaxKind.QuestionQuestionToken].includes(a.operatorToken.kind)) take(a.right);
      };
      take(n.arguments[0]);
    }
    ts.forEachChild(n, visit);
  };
  visit(sf);
}
const enPath = join(root, 'ui/i18n/en.ts');
let old = {};
try { old = (await import(enPath + '?' + Date.now())).en ?? {}; } catch { /* first run */ }
const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`;
const sorted = [...keys.keys()].sort((a, b) => a.localeCompare(b, 'en'));
const body = sorted.map((k) => `  ${q(k)}: ${q(old[k] ?? k)},`).join('\n');
writeFileSync(enPath, `// English interface text: the key is the English text itself (generated by scripts/i18n-extract.mjs; edit plural forms here).\nexport const en = {\n${body}\n} as const;\n`);
console.log(`${sorted.length} keys`);
if (process.env.I18N_SOURCES) writeFileSync(process.env.I18N_SOURCES, JSON.stringify(Object.fromEntries(keys), null, 1));
