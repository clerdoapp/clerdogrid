// Writes docs/functions.md from the function catalog and the registered functions: npm run docs:functions
import { writeFileSync } from 'node:fs';
import { CATALOG, signature } from '../src/engine/catalog';
import { registerAllFunctions } from '../src/engine/functions';
import { functionNames, SPECIAL_FORMS } from '../src/engine/registry';

registerAllFunctions();
// Functions that are registered but by design never compute here (they would run outside code or need a
// service ClerdoGrid doesn't use), and ones that work only with File > Online functions turned on.
const NEVER = new Set(['CALL', 'REGISTER.ID', 'RTD', 'COPILOT', 'FIELDVALUE']);
const ONLINE = new Set(['WEBSERVICE', 'IMAGE', 'STOCKHISTORY', 'IMPORTCSV', 'IMPORTTEXT']);
const have = new Set<string>([...functionNames(), ...SPECIAL_FORMS].filter((n) => !NEVER.has(n)));
const byCat = new Map<string, typeof CATALOG[number][]>();
for (const f of CATALOG) byCat.set(f.category, [...(byCat.get(f.category) ?? []), f]);
const total = CATALOG.filter((f) => have.has(f.name)).length;
const lines = [
  '# Worksheet functions',
  '',
  `ClerdoGrid calculates ${total} worksheet functions. Functions marked *internet* fetch data over https only after you turn on File > Online functions > Allow functions to use the internet; until then they return \`#CONNECT!\`. TRANSLATE and DETECTLANGUAGE use the browser's built-in, on-device translator when it has one. Functions marked *not available* need a service or outside code that ClerdoGrid never uses.`,
  '',
  'This page is generated by `npm run docs:functions`.',
  '',
  ...[...byCat.keys()].sort().map((c) => `- [${c}](#${c.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}) (${byCat.get(c)!.length})`),
  '',
];
for (const c of [...byCat.keys()].sort()) {
  lines.push(`## ${c}`, '', '| Function | What it does |', '|---|---|');
  for (const f of byCat.get(c)!.sort((a, b) => a.name.localeCompare(b.name))) {
    const mark = !have.has(f.name) ? ' *(not available)*' : ONLINE.has(f.name) ? ' *(internet)*' : '';
    lines.push(`| \`${signature(f).replace(/\|/g, '\\|')}\` | ${f.about}${mark} |`);
  }
  lines.push('');
}
writeFileSync('docs/functions.md', lines.join('\n'));
console.log(`docs/functions.md: ${total} functions`);
