// Writes docs/functions.md from the function catalog and the registered functions: npm run docs:functions
import { writeFileSync } from 'node:fs';
import { CATALOG, signature } from '../src/engine/catalog';
import { registerAllFunctions } from '../src/engine/functions';
import { functionNames, SPECIAL_FORMS } from '../src/engine/registry';

registerAllFunctions();
const have = new Set<string>([...functionNames(), ...SPECIAL_FORMS]);
const byCat = new Map<string, typeof CATALOG[number][]>();
for (const f of CATALOG) byCat.set(f.category, [...(byCat.get(f.category) ?? []), f]);
const total = CATALOG.filter((f) => have.has(f.name)).length;
const lines = [
  '# Worksheet functions',
  '',
  `ClerdoGrid calculates ${total} worksheet functions. Functions marked *offline* need an internet service and return \`#CONNECT!\`, because ClerdoGrid never sends your data anywhere.`,
  '',
  'This page is generated by `npm run docs:functions`.',
  '',
  ...[...byCat.keys()].sort().map((c) => `- [${c}](#${c.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}) (${byCat.get(c)!.length})`),
  '',
];
for (const c of [...byCat.keys()].sort()) {
  lines.push(`## ${c}`, '', '| Function | What it does |', '|---|---|');
  for (const f of byCat.get(c)!.sort((a, b) => a.name.localeCompare(b.name))) {
    lines.push(`| \`${signature(f).replace(/\|/g, '\\|')}\` | ${f.about}${have.has(f.name) ? '' : ' *(offline)*'} |`);
  }
  lines.push('');
}
writeFileSync('docs/functions.md', lines.join('\n'));
console.log(`docs/functions.md: ${total} functions`);
